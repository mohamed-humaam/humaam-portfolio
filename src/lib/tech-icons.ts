/**
 * Brand icon for a skill name as entered in the admin ("PHP / Laravel",
 * "Git / GitHub"...). The first keyword that matches wins, so the order
 * below matters: "react native" must be tested before "react".
 */
const MATCHERS: [RegExp, SimpleIcon][] = [
  [/react native/i, siReact],
  [/next/i, siNextdotjs],
  [/react/i, siReact],
  [/typescript/i, siTypescript],
  [/tailwind/i, siTailwindcss],
  [/vue|nuxt/i, siVuedotjs],
  [/html|css/i, siHtml5],
  [/laravel|php/i, siLaravel],
  [/node/i, siNodedotjs],
  [/python|django/i, siPython],
  [/\.net|c#/i, siDotnet],
  [/rust/i, siRust],
  [/graphql/i, siGraphql],
  [/expo/i, siExpo],
  [/flutter|dart/i, siFlutter],
  [/postgres/i, siPostgresql],
  [/mysql/i, siMysql],
  [/mongo/i, siMongodb],
  [/redis/i, siRedis],
  [/prisma/i, siPrisma],
  [/firebase/i, siFirebase],
  [/cloudflare/i, siCloudflare],
  [/vercel/i, siVercel],
  [/docker/i, siDocker],
  [/linux|vps/i, siLinux],
  [/ci\/cd|actions/i, siGithubactions],
  [/git/i, siGit],
  [/figma/i, siFigma],
  [/postman/i, siPostman],
  [/jira|linear/i, siJira],
];

export function techIcon(name: string): SimpleIcon | null {
  return MATCHERS.find(([pattern]) => pattern.test(name))?.[1] ?? null;
}
